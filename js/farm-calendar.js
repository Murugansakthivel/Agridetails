/* Agridetails — Smart Farm Calendar.
   Personalized task list, saved in localStorage only (no backend yet).
   Auto-suggests a generic stage-based task schedule when a Farm Profile
   with a sowing date exists (offsets are commonly-cited agronomy
   generalizations, not crop/variety-specific — always presented as a
   starting point, not certainty, per the site's no-fabricated-precision
   rule). Farmers can add/edit/delete/complete any task freely. */
(function () {
  'use strict';

  const KEY = 'agri_farm_calendar_v1';
  const PROFILE_KEY = 'agri_farm_profile_v1';

  function t(key) { return I18N[currentLang()][key] || I18N.en[key] || key; }

  function loadTasks() {
    try { return JSON.parse(localStorage.getItem(KEY) || '[]'); } catch (e) { return []; }
  }
  function saveTasks(tasks) { localStorage.setItem(KEY, JSON.stringify(tasks)); }
  function loadProfile() {
    try { return JSON.parse(localStorage.getItem(PROFILE_KEY) || 'null'); } catch (e) { return null; }
  }

  // Generic stage-based task template, offset in days from sowing date.
  // These are widely-cited general practice windows (not variety-specific
  // agronomy advice) — always shown with a caveat to confirm locally.
  const GENERIC_SCHEDULE = [
    { offsetDays: 0, type: 'sowing', icon: '🌱' },
    { offsetDays: 7, type: 'irrigation', icon: '💧' },
    { offsetDays: 15, type: 'fertilizer_basal', icon: '🧪' },
    { offsetDays: 21, type: 'weed_control', icon: '🌿' },
    { offsetDays: 30, type: 'inspection', icon: '🔍' },
    { offsetDays: 35, type: 'fertilizer_top', icon: '🧪' },
    { offsetDays: 45, type: 'pest_check', icon: '🐛' },
    { offsetDays: 60, type: 'irrigation2', icon: '💧' },
    { offsetDays: 75, type: 'pre_harvest_check', icon: '🔍' },
    { offsetDays: 90, type: 'harvest_window', icon: '🌾' }
  ];

  function addDays(dateStr, days) {
    const d = new Date(dateStr);
    d.setDate(d.getDate() + days);
    return d.toISOString().slice(0, 10);
  }

  function genId() { return 'task_' + Date.now() + '_' + Math.random().toString(36).slice(2, 8); }

  function generateFromProfile(profile) {
    if (!profile || !profile.sowingDate || !profile.crops || !profile.crops.length) return [];
    const existing = loadTasks();
    const already = new Set(existing.filter(x => x.autoGenerated).map(x => x.autoKey));
    const generated = [];
    profile.crops.forEach(crop => {
      GENERIC_SCHEDULE.forEach(step => {
        const autoKey = crop + '|' + step.offsetDays + '|' + profile.sowingDate;
        if (already.has(autoKey)) return;
        generated.push({
          id: genId(),
          date: addDays(profile.sowingDate, step.offsetDays),
          crop: crop,
          type: step.type,
          icon: step.icon,
          done: false,
          autoGenerated: true,
          autoKey: autoKey
        });
      });
    });
    return generated;
  }

  window.initFarmCalendar = function initFarmCalendar() {
    const listEl = document.getElementById('calTaskList');
    const emptyEl = document.getElementById('calEmptyState');
    const addForm = document.getElementById('calAddForm');
    const genBtn = document.getElementById('calGenerateBtn');
    const noProfileNote = document.getElementById('calNoProfileNote');
    const filterSel = document.getElementById('calFilter');
    if (!listEl) return;

    function taskTypeLabel(type) { return t('cal_type_' + type) || type; }

    function render() {
      let tasks = loadTasks();
      const filterVal = filterSel.value;
      const today = new Date().toISOString().slice(0, 10);

      if (filterVal === 'upcoming') tasks = tasks.filter(x => !x.done && x.date >= today);
      else if (filterVal === 'overdue') tasks = tasks.filter(x => !x.done && x.date < today);
      else if (filterVal === 'done') tasks = tasks.filter(x => x.done);

      tasks.sort((a, b) => a.date.localeCompare(b.date));

      if (!tasks.length) {
        emptyEl.hidden = false;
        listEl.innerHTML = '';
        return;
      }
      emptyEl.hidden = true;

      listEl.innerHTML = tasks.map(x => {
        const overdue = !x.done && x.date < today;
        return `<div class="cal-task-row ${x.done ? 'done' : ''} ${overdue ? 'overdue' : ''}" data-id="${x.id}">
          <input type="checkbox" class="cal-task-check" ${x.done ? 'checked' : ''}>
          <span class="cal-task-icon">${x.icon || '📌'}</span>
          <div class="cal-task-body">
            <div class="cal-task-title">${x.title || taskTypeLabel(x.type)}${x.crop ? ' — ' + x.crop : ''}</div>
            <div class="cal-task-date small muted">${x.date}${overdue ? ' · ' + t('cal_overdue') : ''}${x.autoGenerated ? ' · ' + t('cal_suggested') : ''}</div>
          </div>
          <button type="button" class="cal-task-delete" aria-label="Delete">✕</button>
        </div>`;
      }).join('');
    }

    listEl.addEventListener('click', ev => {
      const row = ev.target.closest('.cal-task-row');
      if (!row) return;
      const id = row.dataset.id;
      let tasks = loadTasks();
      if (ev.target.classList.contains('cal-task-check')) {
        tasks = tasks.map(x => x.id === id ? Object.assign({}, x, { done: ev.target.checked }) : x);
        saveTasks(tasks);
        render();
      } else if (ev.target.classList.contains('cal-task-delete')) {
        tasks = tasks.filter(x => x.id !== id);
        saveTasks(tasks);
        render();
      }
    });

    addForm.addEventListener('submit', ev => {
      ev.preventDefault();
      const title = addForm.calTaskTitle.value.trim();
      const date = addForm.calTaskDate.value;
      if (!title || !date) return;
      const tasks = loadTasks();
      tasks.push({ id: genId(), date, title, icon: '📌', done: false, autoGenerated: false });
      saveTasks(tasks);
      addForm.reset();
      render();
    });

    function updateProfileState() {
      const profile = loadProfile();
      const hasProfile = !!(profile && profile.sowingDate && profile.crops && profile.crops.length);
      noProfileNote.hidden = hasProfile;
      genBtn.hidden = !hasProfile;
    }

    if (genBtn) {
      genBtn.addEventListener('click', () => {
        const profile = loadProfile();
        const newTasks = generateFromProfile(profile);
        if (!newTasks.length) return;
        const tasks = loadTasks().concat(newTasks);
        saveTasks(tasks);
        render();
      });
    }

    filterSel.addEventListener('change', render);

    updateProfileState();
    render();

    document.addEventListener('agri:lang', render);
  };
})();
